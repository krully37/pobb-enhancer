// Builds dist/firefox and dist/chrome from src/, plus a .zip of each for the stores.
// Zero dependencies: needs Node >= 22 (zlib.crc32).
import { readFileSync, writeFileSync, mkdirSync, rmSync, readdirSync, statSync } from 'node:fs'
import { join, dirname, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'
import { deflateRawSync, crc32 } from 'node:zlib'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const SRC = join(ROOT, 'src')
const DIST = join(ROOT, 'dist')
const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'))
const base = JSON.parse(readFileSync(join(SRC, 'manifest.base.json'), 'utf8'))

const TARGETS = {
  firefox: {
    ...base,
    version: pkg.version,
    background: { scripts: ['background.js'], type: 'module' },
    browser_specific_settings: {
      gecko: {
        id: '{5d638256-1057-475f-b1d5-862ccc119871}',
        strict_min_version: '140.0',
        data_collection_permissions: { required: ['none'] }
      }
    }
  },
  chrome: {
    ...base,
    version: pkg.version,
    minimum_chrome_version: '111',
    background: { service_worker: 'background.js', type: 'module' }
  }
}

function walk (dir) {
  return readdirSync(dir).flatMap(name => {
    const p = join(dir, name)
    return statSync(p).isDirectory() ? walk(p) : [p]
  })
}

// Minimal zip writer (deflate, no zip64).
function zip (files) {
  const local = []
  const central = []
  let offset = 0
  const time = ((12 << 11) | 0) // 12:00:00
  const date = (((2025 - 1980) << 9) | (1 << 5) | 1) // fixed date => reproducible zips
  for (const { name, data } of files) {
    const nameBuf = Buffer.from(name, 'utf8')
    const comp = deflateRawSync(data, { level: 9 })
    const crc = crc32(data)
    const h = Buffer.alloc(30)
    h.writeUInt32LE(0x04034b50, 0); h.writeUInt16LE(20, 4); h.writeUInt16LE(0x0800, 6); h.writeUInt16LE(8, 8)
    h.writeUInt16LE(time, 10); h.writeUInt16LE(date, 12); h.writeUInt32LE(crc, 14)
    h.writeUInt32LE(comp.length, 18); h.writeUInt32LE(data.length, 22); h.writeUInt16LE(nameBuf.length, 26)
    local.push(h, nameBuf, comp)
    const c = Buffer.alloc(46)
    c.writeUInt32LE(0x02014b50, 0); c.writeUInt16LE(20, 4); c.writeUInt16LE(20, 6); c.writeUInt16LE(0x0800, 8)
    c.writeUInt16LE(8, 10); c.writeUInt16LE(time, 12); c.writeUInt16LE(date, 14); c.writeUInt32LE(crc, 16)
    c.writeUInt32LE(comp.length, 20); c.writeUInt32LE(data.length, 24); c.writeUInt16LE(nameBuf.length, 28)
    c.writeUInt32LE(offset, 42)
    central.push(c, nameBuf)
    offset += h.length + nameBuf.length + comp.length
  }
  const cd = Buffer.concat(central)
  const end = Buffer.alloc(22)
  end.writeUInt32LE(0x06054b50, 0); end.writeUInt16LE(files.length, 8); end.writeUInt16LE(files.length, 10)
  end.writeUInt32LE(cd.length, 12); end.writeUInt32LE(offset, 16)
  return Buffer.concat([...local, cd, end])
}

// Content scripts can't be ES modules, so inline the two lib modules the
// content script needs into one classic script exposing globalThis.PobbEnhancerLib.
function contentLib () {
  const strip = (file) => readFileSync(join(SRC, 'lib', file), 'utf8')
    .replace(/^import .*$/gm, '')
    .replace(/^export (?=function|const|class)/gm, '')
  return Buffer.from([
    '// Generated by scripts/build.mjs from src/lib/pob-item.js and src/lib/pob-build.js. Do not edit.',
    '(() => {',
    strip('pob-item.js'),
    strip('pob-build.js'),
    'globalThis.PobbEnhancerLib = { parseBuildXml, mapImagesToItems }',
    '})()',
    ''
  ].join('\n'))
}

rmSync(DIST, { recursive: true, force: true })
const srcFiles = walk(SRC).filter(p => !p.endsWith('manifest.base.json'))
const iconFiles = walk(join(ROOT, 'icons')).filter(p => p.endsWith('.png'))

for (const [target, manifest] of Object.entries(TARGETS)) {
  const out = join(DIST, target)
  const entries = []
  const add = (rel, data) => {
    const dest = join(out, rel)
    mkdirSync(dirname(dest), { recursive: true })
    writeFileSync(dest, data)
    entries.push({ name: rel.split(sep).join('/'), data })
  }
  add('manifest.json', Buffer.from(JSON.stringify(manifest, null, 2) + '\n'))
  for (const p of srcFiles) add(relative(SRC, p), readFileSync(p))
  add('content-lib.js', contentLib())
  for (const p of iconFiles) add(join('icons', relative(join(ROOT, 'icons'), p)), readFileSync(p))
  entries.sort((a, b) => a.name.localeCompare(b.name))
  const zipPath = join(DIST, `pobb-enhancer-${target}-${pkg.version}.zip`)
  writeFileSync(zipPath, zip(entries))
  console.log(`${target}: ${entries.length} files -> ${relative(ROOT, zipPath)}`)
}

// Source archive for AMO review (no build step, but AMO may still ask).
const sourceFiles = [
  ...walk(join(ROOT, 'src')), ...walk(join(ROOT, 'scripts')), ...walk(join(ROOT, 'test')),
  ...iconFiles, ...['package.json', 'README.md', 'LICENSE'].map(f => join(ROOT, f))
].filter(p => { try { return statSync(p).isFile() } catch { return false } })
writeFileSync(join(DIST, `pobb-enhancer-source-${pkg.version}.zip`), zip(sourceFiles.map(p => ({
  name: relative(ROOT, p).split(sep).join('/'), data: readFileSync(p)
}))))
console.log(`source: ${sourceFiles.length} files -> dist/pobb-enhancer-source-${pkg.version}.zip`)
